export function parseGroundedCommand(value: unknown): GroundedCommand {
  if (!value || typeof value !== "object" || Array.isArray(value))
    throw Error("Invalid grounded command");
  const item = value as Record<string, unknown>;
  if (
    Object.keys(item).sort().join(",") !== "topic,use_model" ||
    typeof item.topic !== "string" ||
    !Object.hasOwn(TOPICS, item.topic) ||
    typeof item.use_model !== "boolean"
  )
    throw Error("Invalid grounded command");
  return { topic: item.topic as GroundedTopic, use_model: item.use_model };
}

/** Pointers are generated by this module, never accepted from a request/provider. */
export function readEvidencePointer(run: ScientificRun, pointer: string): JsonValue {
  let value: unknown = run;
  for (const part of pointer.split("/").slice(1)) {
    if (!value || typeof value !== "object" || !Object.hasOwn(value, part))
      throw Error("Missing report evidence");
    value = (value as Record<string, unknown>)[part];
  }
  return parseStrictJson(canonicalize(value)) as JsonValue;
}
const object = (value: JsonValue) => value as JsonObject;
const metric = (value: JsonValue | undefined): string => {
  const item = value as JsonObject;
  return item.value === null ? `不可用（${String(item.reason)}）` : String(item.value);
};

export function buildEvidence(run: ScientificRun, topic: GroundedTopic): EvidencePack {
  if (
    !Object.hasOwn(TOPICS, topic) ||
    run.status !== "completed" ||
    !run.result ||
    canonicalHash(run.result) !== run.scientific_result_hash ||
    run.identity.algorithm_version !== SCIENTIFIC_ALGORITHM ||
    Object.entries(scientificSettings()).some(
      ([key, value]) => canonicalize(run.configuration[key]) !== canonicalize(value),
    )
  )
    throw Error("Report not complete or intact");
  const sources: EvidenceSource[] = [],
    cards: EvidenceCard[] = [];
  const add = (
    id: string,
    title: string,
    pointer: string,
    render: (value: JsonValue) => string,
  ) => {
    const value = readEvidencePointer(run, pointer);
    sources.push({
      id,
      kind: "report",
      title,
      pointer,
      document: "authorized_scientific_run",
      value,
      hash: canonicalHash(value),
    });
    cards.push({ id, title, text: render(value), citations: [id] });
  };
  const method = (id: keyof typeof METHODS) => {
    const sourceId = `method.${id}`,
      value = METHODS[id];
    sources.push({
      id: sourceId,
      kind: "method",
      title: "本项目方法合同",
      pointer: null,
      document: `src/domain/grounded/evidence.ts#${GROUNDED_VERSION}/${id}`,
      value,
      hash: canonicalHash(value),
    });
    cards.push({ id: sourceId, title: "怎样解读", text: value, citations: [sourceId] });
  };
  const selection = () => {
    for (const [field, title] of [
      ["candidate_count", "封存候选"],
      ["included_count", "纳入记录"],
      ["excluded_count", "未纳入记录"],
    ] as const)
      add(
        `selection.${field}`,
        title,
        `/result/selection/${field}`,
        (value) => `${title}：${value} 条。`,
      );
    method("inclusion");
  };
  const best = () => {
    add("best", "已测条件中的最高均值", "/result/best_tested", (value) => {
      const v = object(value);
      return v.mean === null
        ? `当前不能确定实测最佳（${v.reason}）。`
        : `已测浓度 ${(v.concentrations as number[]).join("%、")}%；平均得率 ${v.mean}%。并列条件均保留。`;
    });
    method("best");
  };
  const candidate = () => {
    add("candidate", "待验证候选", "/result/candidate", (value) => {
      const v = object(value);
      return v.concentration === null
        ? `本报告未给出候选浓度（${v.reason}），不补算或猜测一个值。`
        : `候选浓度 ${v.concentration}%；模型预测得率 ${v.predicted_yield}%。删组顶点范围 ${(v.leave_one_out_vertex_range as number[]).join("–")}%。`;
    });
    method("candidate");
  };
  if (topic === "overview" || topic === "inclusion") selection();
  if (topic === "overview" || topic === "best") best();
  if (topic === "overview" || topic === "candidate") candidate();
  if (["descriptive", "uncertainty", "outliers"].includes(topic)) {
    const groups = run.result.groups as JsonObject[];
    groups.forEach((group, i) => {
      const id = `group.${i}`,
        title = `${group.concentration}% 浓度组`;
      const concentrationId = `${id}.concentration`;
      const concentration = readEvidencePointer(run, `/result/groups/${i}/concentration`);
      sources.push({
        id: concentrationId,
        kind: "report",
        title: "浓度 (%)",
        pointer: `/result/groups/${i}/concentration`,
        document: "authorized_scientific_run",
        value: concentration,
        hash: canonicalHash(concentration),
      });
      const firstCard = cards.length;
      add(
        `${id}.n`,
        `${title}记录数`,
        `/result/groups/${i}/n`,
        (value) => `${title}纳入 ${value} 条记录。`,
      );
      if (topic === "descriptive")
        add(`${id}.statistics`, title, `/result/groups/${i}/statistics`, (value) => {
          const v = object(value);
          return `${title}：平均得率 ${metric(v.mean)}%；样本 SD ${metric(v.sd)}；原始 MAD ${metric(v.mad)}。不可用指标不能解释为零。`;
        });
      if (topic === "uncertainty")
        add(`${id}.ci`, title, `/result/groups/${i}/ci`, (value) => {
          const v = object(value);
          return v.lower === null
            ? `${title}区间不可用（${v.reason}）。`
            : `${title}均值的 95% bootstrap 区间为 ${v.lower}–${v.upper}%。`;
        });
      if (topic === "outliers")
        add(`${id}.flags`, title, `/result/groups/${i}/iqr_flags`, (value) => {
          const v = object(value);
          return v.reason === null
            ? `${title}标记 ${(v.record_ids as JsonValue[]).length} 条记录；标记不是删除指令。`
            : `${title}未应用标记规则（${v.reason}）。`;
        });
      for (const card of cards.slice(firstCard)) card.citations.push(concentrationId);
    });
    method(topic as "descriptive" | "uncertainty" | "outliers");
  }
  if (topic === "validation") {
    add("validation", "留一浓度交叉验证", "/result/regression/loocv", (value) => {
      const v = object(value);
      return v.available
        ? `留一浓度 RMSE：${metric(v.rmse)} 个得率百分点。逐折实测、预测与外推标记见引用原值。`
        : `交叉验证不可用（${v.reason}）；不以训练拟合优度代替验证。`;
    });
    method("validation");
  }
  add(
    "limitations",
    "报告记录的限制",
    "/result/limitations",
    () =>
      "报告明确保留探索性、独立性未核实、bootstrap 前提、四浓度模型和新实验验证等限制；详见引用原值。",
  );
  method("limitations");
  const content: Omit<EvidencePack, "evidence_hash"> = {
    schema: GROUNDED_VERSION,
    topic,
    run_id: run.id,
    dataset_hash: run.dataset_hash,
    scientific_result_hash: run.scientific_result_hash,
    execution_fingerprint: run.execution_fingerprint,
    sources,
    cards,
  };
  return { ...content, evidence_hash: canonicalHash(content) };
}

/** A model can reorder, never add/remove a claim, caution, citation or number. */
export function validateCardOrder(raw: unknown, cards: EvidenceCard[]): string[] {
  if (typeof raw !== "string" || Buffer.byteLength(raw) > 4096)
    throw Error("Invalid card ordering");
  const value = parseStrictJson(raw) as Record<string, unknown>;
  const allowed = cards.map((card) => card.id);
  if (
    !value ||
    typeof value !== "object" ||
    Array.isArray(value) ||
    Object.keys(value).join(",") !== "card_ids" ||
    !Array.isArray(value.card_ids) ||
    value.card_ids.length !== allowed.length ||
    value.card_ids.some((id) => typeof id !== "string" || !allowed.includes(id)) ||
    new Set(value.card_ids).size !== allowed.length
  )
    throw Error("Invalid card ordering");
  return value.card_ids as string[];
}
